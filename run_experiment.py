"""End-to-end run: features -> classifiers -> evaluation -> ablation -> figures.

    python run_experiment.py                 # all three branches
    python run_experiment.py --branch heart  # one branch
    python run_experiment.py --no-cache      # force feature re-extraction
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import config
from src import visualize as viz
from src.ablation import run_ablation
from src.datasets import load_domain
from src.pipeline import build_features
from src.preprocess import preprocess
from src.train import best_model_name, evaluate_branch

BRANCHES = ["music", "heart", "respiratory"]
BRANCH_TITLE = {"music": "Music branch (M4a)",
                "heart": "Medical branch - heart sounds (M4b)",
                "respiratory": "Medical branch - respiratory sounds (M4b)"}


def sample_figures(domain):
    cfg = config.DOMAINS[domain]
    records, _ = load_domain(domain, limit_per_class=1)
    seen = set()
    for sig, sr_in, lab, _grp in records:
        if lab in seen:
            continue
        seen.add(lab)
        x, sr = preprocess(sig, sr_in, cfg)
        viz.signal_overview(x, sr, cfg, f"{domain} / {lab}",
                            config.FIGURES / f"overview_{domain}_{lab}.png")
    viz.filterbank_figure(cfg, config.FIGURES / f"melbank_{domain}.png")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--branch", choices=BRANCHES, action="append")
    ap.add_argument("--no-cache", action="store_true")
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--skip-figures", action="store_true")
    args = ap.parse_args()

    branches = args.branch or BRANCHES
    summary, ablations, all_results = {}, {}, {}

    for b in branches:
        cfg = config.DOMAINS[b]
        print(f"\n=== {BRANCH_TITLE[b]} ===")
        X, y, groups, names, source = build_features(
            b, args.limit, use_cache=not args.no_cache)
        labels = [c for c in cfg["classes"] if c in set(y)]

        results, _ = evaluate_branch(X, y, labels, groups=groups)
        best = best_model_name(results)
        print(f"  data source : {source}")
        print(f"  features    : {X.shape[1]}   samples: {X.shape[0]}   "
              f"groups: {len(set(groups))}")
        for name, r in results.items():
            extra = ""
            if "sensitivity" in r:
                extra = f"  sens={r['sensitivity']:.3f} spec={r['specificity']:.3f}"
            print(f"  {name:<15} cv={r['cv_mean']:.3f}+/-{r['cv_std']:.3f}  "
                  f"test={r['test_accuracy']:.3f}  bal={r['balanced_accuracy']:.3f}  "
                  f"macroF1={r['macro_f1']:.3f}{extra}")
        print(f"  best        : {best}")

        rows = run_ablation(X, y, names, best, groups=groups)
        ablations[b] = rows
        print("  ablation:")
        for r in rows:
            print(f"    {r['configuration']:<20} n={r['n_features']:<3} "
                  f"acc={r['cv_accuracy']:.3f}  d={r['delta']:+.3f}")

        all_results[b] = results
        summary[b] = {
            "source": source, "n_samples": int(X.shape[0]),
            "n_groups": int(len(set(groups))),
            "n_features": int(X.shape[1]), "classes": labels,
            "best_classifier": best,
            "classifiers": {k: {kk: vv for kk, vv in v.items() if kk != "model"}
                            for k, v in results.items()},
            "ablation": rows,
        }

        if not args.skip_figures:
            viz.confusion_grid(results, labels, BRANCH_TITLE[b],
                               config.FIGURES / f"confusion_{b}.png")
            viz.feature_scatter(X, y, names, config.FIGURES / f"pca_{b}.png",
                                f"Feature-space separation - {b}")
            sample_figures(b)

    if not args.skip_figures and len(all_results) > 1:
        viz.classifier_comparison(all_results, config.FIGURES / "classifier_comparison.png")
        viz.ablation_figure(ablations, config.FIGURES / "ablation.png")

    out = config.TABLES / "results.json"
    out.write_text(json.dumps(summary, indent=2))
    print(f"\nSaved {out}")
    print(f"Figures in {config.FIGURES}")
    _write_markdown(summary)


def _write_markdown(summary):
    L = ["# Results\n",
         "Generated by `run_experiment.py`. `source` states whether the numbers",
         "come from the real Kaggle dataset or the synthetic pipeline check.\n"]
    for b, s in summary.items():
        L.append(f"\n## {b}  (source: `{s['source']}`)\n")
        L.append(f"Samples: {s['n_samples']} | Features: {s['n_features']} | "
                 f"Classes: {', '.join(s['classes'])}\n")
        binary = "sensitivity" in next(iter(s["classifiers"].values()))
        head = "| Classifier | CV acc | Test acc | Balanced acc | Macro F1 |"
        sep = "|---|---|---|---|---|"
        if binary:
            head += " Sensitivity | Specificity |"
            sep += "---|---|"
        L += [head, sep]
        for k, v in s["classifiers"].items():
            row = (f"| {k} | {v['cv_mean']:.3f} ± {v['cv_std']:.3f} | "
                   f"{v['test_accuracy']:.3f} | {v['balanced_accuracy']:.3f} | "
                   f"{v['macro_f1']:.3f} |")
            if binary:
                row += f" {v['sensitivity']:.3f} | {v['specificity']:.3f} |"
            L.append(row)
        L.append(f"\nBest: **{s['best_classifier']}**\n")
        L += ["\n| Ablation | #Feat | CV acc | Δ |", "|---|---|---|---|"]
        for r in s["ablation"]:
            L.append(f"| {r['configuration']} | {r['n_features']} | "
                     f"{r['cv_accuracy']:.3f} | {r['delta']:+.3f} |")
    (config.RESULTS / "RESULTS.md").write_text("\n".join(L), encoding="utf-8")
    print(f"Saved {config.RESULTS / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
